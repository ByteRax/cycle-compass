# -*- coding: utf-8 -*-
"""打分系统校准验证：用笔记披露的真实样例点，验证推断公式能否复现笔记结果。
数据来源：xcnbeta「指数轮动笔记」图集 OCR 识别（result1~5.md）。
"""
from scoring import ScoreInput, evaluate, tech_score, spread_score, value_score, style_score

# 完整链路验证点：(名称, pe分位, 股息率, 国债, RSI70, %B100, 风格分位, 笔记总分)
FULL = [
    ("G13 10-13", 0.846, 4.41, 1.67, 50, 0.64, 0.45, 9.2),
    ("G28 11-03", 0.870, 4.58, 1.62, 53, 0.99, 0.62, 7.00),
    ("G35 11-20", 0.900, 4.49, 1.58, 54, 0.96, 0.75, 6.72),
]

# 四维分 → 总分 验证点：(名称, 技术, 利差, 估值, 风格, 笔记总分)
DIM = [
    ("G12 10-12", 41.6, 68.0, 21.2, 55.0, 9.3),
    ("G13 10-13", 42.6, 68.5, 15.4, 55.0, 9.2),
    ("G16 10-14", 36.8, 68.8, 15.2, 54.0, 8.7),
    ("G18 10-23", 53.2, 72.1, 14.9, 46.6, 10.3),
    ("G20 10-28", 43.8, 73.6, 13.9, 44.8, 9.4),
    ("G22 10-29", 40.0, 73.0, 14.0, 42.0, 8.91),
    ("G26 10-30", 34.0, 73.7, 13.1, 40.1, 8.28),
    ("G28 11-03", 21.5, 73.9, 13.0, 38.2, 7.00),
    ("G30 11-06", 22.7, 74.8, 14.4, 40.4, 7.25),
    ("G32 11-13", 31.9, 73.1, 14.0, 39.8, 8.06),
    ("G35 11-20", 22.7, 72.8, 10.2, 25.0, 6.72),
]

print("=" * 78)
print("A. 完整链路验证：原始指标 → 四维分 → 总分")
print("=" * 78)
print(f"{'样例':<12}{'技术':>7}{'利差':>7}{'估值':>7}{'风格':>7}{'计算总分':>10}{'笔记总分':>10}{'误差':>7}")
for name, pep, dy, bond, rsi, bp, sp, ref in FULL:
    r = evaluate(ScoreInput(pep, dy, bond, rsi, bp, sp))
    print(f"{name:<12}{r.tech:>7.1f}{r.spread:>7.1f}{r.value:>7.1f}{r.style:>7.1f}"
          f"{r.total:>10.2f}{ref:>10.2f}{r.total-ref:>+7.2f}")

print()
print("=" * 78)
print("B. 四维加权验证：已知四维分 → 总分（权重 50/25/15/10，除以5）")
print("=" * 78)
from scoring import total_score
print(f"{'样例':<12}{'技术':>7}{'利差':>7}{'估值':>7}{'风格':>7}{'计算总分':>10}{'笔记总分':>10}{'误差':>7}")
errs = []
for name, t, s, v, st, ref in DIM:
    calc = total_score(t, s, v, st)
    errs.append(abs(calc - ref))
    print(f"{name:<12}{t:>7.1f}{s:>7.1f}{v:>7.1f}{st:>7.1f}{calc:>10.2f}{ref:>10.2f}{calc-ref:>+7.2f}")
print(f"\n平均绝对误差 = {sum(errs)/len(errs):.3f} 分；最大误差 = {max(errs):.3f} 分")

print()
print("=" * 78)
